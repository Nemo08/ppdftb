// ╤З╨╕╤Б╨╗╨░-╨║╨╡╤А╨╜╨╕╨╜╨│╨╕ ╨┐╤А╨╕╨▓╤П╨╖╨░╨╜╤Л ╨║ ╨┐╤А╨╡╨┤╤И╨╡╤Б╤В╨▓╤Г╤О╤Й╨╡╨╝╤Г ╨╗╨╕╤В╨╡╤А╨░╨╗╤Г. ╨б╨╛╨┐╨╛╤Б╤В╨░╨▓╨╗╨╡╨╜╨╕╨╡ ╤Б╤В╤А╨╛╨╕╤В╤Б╤П
// ╨╜╨░ ╤З╨╕╤Б╨╗╨╡ ╨▒╨░╨╣╤В╨╛╨▓ ╨╜╨░ ╤Б╨╕╨╝╨▓╨╛╨╗ (2 ╨┤╨╗╤П ╨║╨╛╨╝╨┐╨╛╨╖╨╕╤В╨╜╤Л╤Е CID-╤И╤А╨╕╤Д╤В╨╛╨▓, 1 ╨┤╨╗╤П ╨┐╤А╨╛╤Б╤В╤Л╤Е),
// ╨║╨╛╤В╨╛╤А╨╛╨╡ ╤Б╨▓╨╡╤А╤П╨╡╤В╤Б╤П ╤Б ╨┐╨╛╨╗╨╜╨╛╨╣ ╨┤╨╗╨╕╨╜╨╛╨╣ ╨╗╨╕╤В╨╡╤А╨░╨╗╨╛╨▓ ╨╛╨┐╨╡╤А╨░╨╜╨┤╨░ тАФ ╨┐╤А╨╕ ╤А╨░╤Б╤Е╨╛╨╢╨┤╨╡╨╜╨╕╨╕ (╨╕╨╗╨╕
// ╨╛╤В╤Б╤Г╤В╤Б╤В╨▓╨╕╨╕ ╤В╨╛╨║╨╡╨╜╨╛╨▓) ╨▓╨╛╨╖╨▓╤А╨░╤Й╨░╨╡╤В╤Б╤П ok=false ╨╕ ╨┐╨╛╨╗╨╡ ╨┐╤А╨╛╨┐╤Г╤Б╨║╨░╨╡╤В╤Б╤П ╤Ж╨╡╨╗╨╕╨║╨╛╨╝.
func splitRunOperand(toks []token, r streamRun, lo, hi int) fragmentSplit {
	loR := utf8.RuneCountInString(r.text[:lo])
	hiR := utf8.RuneCountInString(r.text[:hi])

	first, last := operandLiteralSpan(toks, r)
	if first < 0 {
		return fragmentSplit{}
	}
	var total int
	for p := first; p <= last; p++ {
		if k := toks[p].kind; k == tokHex || k == tokStr {
			total += len(toks[p].text)
		}
	}
	n := utf8.RuneCountInString(r.text)
	bpc := 0
	if total == n*2 {
		bpc = 2
	} else if total == n {
		bpc = 1
	}
	if bpc == 0 {
		return fragmentSplit{}
	}

	// ╨У╤А╨░╨╜╨╕╤Ж╤Л ╤Д╤А╨░╨│╨╝╨╡╨╜╤В╨░ ╨▓ ╨▒╨░╨╣╤В╨╛╨▓╨╛╨╝ ╨┐╤А╨╛╤Б╤В╤А╨░╨╜╤Б╤В╨▓╨╡ ╨╗╨╕╤В╨╡╤А╨░╨╗╨╛╨▓ ╨╛╨┐╨╡╤А╨░╨╜╨┤╨░.
	loB, hiB := loR*bpc, hiR*bpc

	var pre, suf strings.Builder
	rawPos := 0   // ╨╜╨░╨║╨╛╨┐╨╗╨╡╨╜╨╜╤Л╨╡ ╨▒╨░╨╣╤В╤Л ╨╗╨╕╤В╨╡╤А╨░╨╗╨╛╨▓ ╤Б╨╗╨╡╨▓╨░ ╨╜╨░╨┐╤А╨░╨▓╨╛
	prevZone := 0 // ╨╖╨╛╨╜╨░ ╨┐╨╛╤Б╨╗╨╡╨┤╨╜╨╡╨│╨╛ ╨╗╨╕╤В╨╡╤А╨░╨╗╨░: 1 тАФ ╨┐╤А╨╡╤Д╨╕╨║╤Б, 2 тАФ ╤Б╤Г╤Д╤Д╨╕╨║╤Б, 0 тАФ ╤Д╤А╨░╨│╨╝╨╡╨╜╤В
	for p := first; p <= last; p++ {
		tk := toks[p]
		switch tk.kind {
		case tokNum:
			// ╨з╨╕╤Б╨╗╨╛-╨║╨╡╤А╨╜╨╕╨╜╨│ ╨┐╨╛╨╖╨╕╤Ж╨╕╨╛╨╜╨╕╤А╤Г╨╡╤В ╤Б╨╗╨╡╨┤╤Г╤О╤Й╨╕╨╣ ╨╖╨░ ╨╗╨╕╤В╨╡╤А╨░╨╗╨╛╨╝ ╨│╨╗╨╕╤Д: ╨╛╨╜╨╛
			// ╨╛╤Б╤В╨░╤С╤В╤Б╤П ╨▓ ╤В╨╛╨╣ ╨╢╨╡ ╨╖╨╛╨╜╨╡, ╤З╤В╨╛ ╨╕ ╨┐╤А╨╡╨┤╤И╨╡╤Б╤В╨▓╤Г╤О╤Й╨╕╨╣ ╨╗╨╕╤В╨╡╤А╨░╨╗. ╨У╤А╨░╨╜╨╕╤З╨╜╤Л╨╣
			// ╨║╨╡╤А╨╜╨╕╨╜╨│ ╨┐╨╡╤А╨╡╨┤ ╤Д╤А╨░╨│╨╝╨╡╨╜╤В╨╛╨╝ ╨┐╨╛╨┐╨░╨┤╨░╨╡╤В ╨▓ ╨┐╤А╨╡╤Д╨╕╨║╤Б тАФ ╨╖╨╜╨░╤З╨╡╨╜╨╕╨╡ ╤А╨╕╤Б╤Г╨╡╤В╤Б╤П
			// ╤А╨╛╨▓╨╜╨╛ ╤Б ╤В╨╛╨╣ ╤В╨╛╤З╨║╨╕, ╨│╨┤╨╡ ╨▓ ╨╛╤А╨╕╨│╨╕╨╜╨░╨╗╨╡ ╤Б╤В╨╛╤П╨╗ ╨┐╨╡╤А╨▓╤Л╨╣ ╨│╨╗╨╕╤Д ╨┐╨╗╨╡╨╣╤Б╤Е╨╛╨╗╨┤╨╡╤А╨░.
			switch prevZone {
			case 1:
				pre.WriteByte(' ')
				pre.WriteString(tk.text)
			case 2:
				suf.WriteByte(' ')
				suf.WriteString(tk.text)
			}
		case tokHex, tokStr:
			n := len(tk.text)
			start := rawPos
			end := start + n
			rawPos = end
			zone := 0
			if start < loB {
				cut := end
				if cut > loB {
					cut = loB
				}
				writeLiteral(&pre, tk, 0, cut-start)
				zone = 1
			}
			if end > hiB {
				cut := start
				if cut < hiB {
					cut = hiB
				}
				writeLiteral(&suf, tk, cut-start, end-start)
				zone = 2
			}
			prevZone = zone
		}
	}

	sp := fragmentSplit{ok: true}
	if strings.TrimSpace(pre.String()) != "" {
		sp.prefix = "[ " + strings.TrimSpace(pre.String()) + " ] TJ"
	}
	if strings.TrimSpace(suf.String()) != "" {
		sp.suffix = "[ " + strings.TrimSpace(suf.String()) + " ] TJ"
	}
	return sp
}

// operandLiteralSpan ╨▓╨╛╨╖╨▓╤А╨░╤Й╨░╨╡╤В ╨┤╨╕╨░╨┐╨░╨╖╨╛╨╜ ╨╕╨╜╨┤╨╡╨║╤Б╨╛╨▓ ╤В╨╛╨║╨╡╨╜╨╛╨▓ ╨╛╨┐╨╡╤А╨░╨╜╨┤╨░ ╨┐╨╛╨║╨░╨╖╨░ ╤А╨░╨╜╨░
// ([+1..-1] ╨┤╨╗╤П TJ тАФ ╨▓╨║╨╗╤О╤З╨░╤П ╤З╨╕╤Б╨╗╨░-╨║╨╡╤А╨╜╨╕╨╜╨│╨╕, ╨╡╨┤╨╕╨╜╤Б╤В╨▓╨╡╨╜╨╜╤Л╨╣ ╨╗╨╕╤В╨╡╤А╨░╨╗ ╨┤╨╗╤П Tj).
// ╨Ю╤В╤А╨╕╤Ж╨░╤В╨╡╨╗╤М╨╜╤Л╨╣ first тАФ ╨╛╨┐╨╡╤А╨░╨╜╨┤ ╨╜╨╡ ╤А╨░╤Б╨┐╨╛╨╖╨╜╨░╨╜.
func operandLiteralSpan(toks []token, r streamRun) (int, int) {
	if r.opType == "Tj" {
		p := r.opTok - 1 // ╨╗╨╕╤В╨╡╤А╨░╨╗ Tj: ((...)) ╨╗╨╕╨▒╨╛ <...>
		if p >= 0 && (toks[p].kind == tokHex || toks[p].kind == tokStr) {
			return p, p
		}
		return -1, -1
	}
	for open := r.opTok - 1; open >= 0; open-- {
		if toks[open].kind == tokOpen {
			return open + 1, r.opTok - 1
		}
	}
	return -1, -1
}

// writeLiteral ╨╖╨░╨┐╨╕╤Б╤Л╨▓╨░╨╡╤В ╨▒╨░╨╣╤В╨╛╨▓╤Л╨╣ ╨┐╨╛╨┤╨┤╨╕╨░╨┐╨░╨╖╨╛╨╜ [lo,hi) ╨╗╨╕╤В╨╡╤А╨░╨╗╨░ ╤В╨╛╨║╨╡╨╜╨░ ╨▓
// ╨┐╨╛╤В╨╛╨║╨╛╨▓╨╛╨╣ ╤Д╨╛╤А╨╝╨╡ (╨│╨╡╨║╤Б-╨╗╨╕╤В╨╡╤А╨░╨╗ <...> ╨╗╨╕╨▒╨╛ ╤Б╤В╤А╨╛╨║╨░ (...) ╤Б ╤Н╨║╤А╨░╨╜╨╕╤А╨╛╨▓╨░╨╜╨╕╨╡╨╝).
func writeLiteral(sb *strings.Builder, tk token, lo, hi int) {
	sb.WriteByte(' ')
	body := tk.text[lo:hi]
	switch tk.kind {
	case tokHex:
		sb.WriteString("<" + hexEncode([]byte(body)) + ">")
	default:
		sb.WriteString("(" + quoteString(body) + ")")
	}
}

// composePartialRun ╤Б╨╛╨▒╨╕╤А╨░╨╡╤В ╨╛╨┐╨╡╤А╨░╤В╨╛╤А╨╜╤Г╤О ╨┐╨╛╤Б╨╗╨╡╨┤╨╛╨▓╨░╤В╨╡╨╗╤М╨╜╨╛╤Б╤В╤М ╨┤╨╗╤П ╤А╨░╨╜╨░ ╤Б
// ╤З╨░╤Б╤В╨╕╤З╨╜╤Л╨╝ ╤Д╤А╨░╨│╨╝╨╡╨╜╤В╨╛╨╝: ╤Б╤В╨░╤В╨╕╤З╨╜╤Л╨╣ ╨┐╤А╨╡╤Д╨╕╨║╤Б/╤Б╤Г╤Д╤Д╨╕╨║╤Б (╨▓ ╨╕╤Б╤Е╨╛╨┤╨╜╨╛╨╝ ╤И╤А╨╕╤Д╤В╨╡ ra╤А╨░),
// ╨╖╨╜╨░╤З╨╡╨╜╨╕╨╡ ╨▓ ╤В╨╛╤З╨║╨╡ ╤Д╤А╨░╨│╨╝╨╡╨╜╤В╨░ ╤Б ╨┐╨╡╤А╨╡╨║╨╗╤О╤З╨╡╨╜╨╕╨╡╨╝ ╨╜╨░ ╨▓╨╜╨╡╨┤╤А╤С╨╜╨╜╤Л╨╣ ╤И╤А╨╕╤Д╤В (╨╡╤Б╨╗╨╕ ╨╜╤Г╨╢╨╡╨╜
// FontName) ╨╕ ╨▓╨╛╤Б╤Б╤В╨░╨╜╨╛╨▓╨╗╨╡╨╜╨╕╨╡╨╝ ╨╕╤Б╤Е╨╛╨┤╨╜╨╛╨│╨╛ Tf ╨┐╨╛╤Б╨╗╨╡ ╨╖╨╜╨░╤З╨╡╨╜╨╕╤П.
func composePartialRun(r streamRun, sp fragmentSplit, codec RunCodec, value string, delta, size float64) string {
	var sb strings.Builder
	if sp.prefix != "" {
		sb.WriteString(sp.prefix)
		sb.WriteByte(' ')
	}
	needSwitch := codec != nil && codec.FontName() != ""
	if needSwitch {
		sb.WriteString(codec.FontName())
		sb.WriteByte(' ')
		sb.WriteString(fmtNum(size))
		sb.WriteString(" Tf ")
	}
	sb.WriteString(renderOperand(value, delta, codec))
	if needSwitch {
		sb.WriteByte(' ')
		sb.WriteString(r.font)
		sb.WriteByte(' ')
		sb.WriteString(fmtNum(size))
		sb.WriteString(" Tf")
	}
	if sp.suffix != "" {
		sb.WriteByte(' ')
		sb.WriteString(sp.suffix)
	}
	return sb.String()
}
